// ===== LANGUAGE ENGINE =====
function applyLanguage(lang) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

    document.documentElement.lang = lang === "ka" ? "ka" : "en";

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
    });

    const titleKey = document.body.getAttribute("data-i18n-title");
    if (titleKey && dict[titleKey]) document.title = dict[titleKey];

    const toggleBtn = document.getElementById("lang-toggle");
    if (toggleBtn) toggleBtn.textContent = dict["lang.toggle"];

    localStorage.setItem("site-lang", lang);
}

function initLanguage() {
    const saved = localStorage.getItem("site-lang") || "ka";
    applyLanguage(saved);

    const toggleBtn = document.getElementById("lang-toggle");
    if (toggleBtn) {
        toggleBtn.addEventListener("click", () => {
            const current = localStorage.getItem("site-lang") || "en";
            applyLanguage(current === "en" ? "ka" : "en");
        });
    }
}

document.addEventListener("DOMContentLoaded", initLanguage);
